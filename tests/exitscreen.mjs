// UI test for the Exit pack section: validation, the no-passphrase confirmation, a run, and the audit entry.
import { JSDOM } from 'jsdom';
import { readFileSync } from 'node:fs';
import { makeFake } from '../fake-supabase.js';
const dom = new JSDOM(readFileSync(new URL('../index.html', import.meta.url), 'utf8').replace(/<script[\s\S]*?<\/script>/g, ''), { url: 'https://app.test/', pretendToBeVisual: true });
const { window } = dom;
const D = window.HTMLDialogElement.prototype;
Object.defineProperty(D, 'open', { get() { return this.hasAttribute('open'); }, configurable: true });
D.showModal = function () { this.setAttribute('open', ''); };
D.close = function () { if (this.hasAttribute('open')) { this.removeAttribute('open'); this.dispatchEvent(new window.Event('close')); } };
Object.assign(globalThis, { window, document: window.document, location: window.location, history: window.history, localStorage: window.localStorage });
const api = await import('../api.js'); const { state } = await import('../state.js'); const { mountExit } = await import('../exitscreen.js');
const db = { _rpc: {} };
api.init(makeFake(db)); state.org = { id: 'o1', name: 'T' };
let saved = null; let opts = null;
const box = document.body.appendChild(document.createElement('div'));
mountExit(box, { build: async (o) => { opts = o; o.onProgress({ stage: 'Reading', message: 'x', done: 1, total: 2 }); return { bytes: new Uint8Array([1]), filename: 'p.zip', summary: { problems: 0, size: 1, sheets: 29, tables: [1, 2], documents: { in_pack: 1, in_database: 1 }, encrypted: !!o.passphrase } }; }, saveFile: (b, n) => { saved = n; } });
let bad = 0; const ok = (c, m) => { if (!c) { console.error('FAIL:', m); bad++; } };
const form = () => box.querySelector('#exit-form');
const submit = () => form().dispatchEvent(new window.Event('submit', { cancelable: true, bubbles: true }));
const set = (n, v) => { form().elements[n].value = v; };
set('pass', 'short'); set('pass2', 'short'); submit();
ok(/at least 12/.test(box.textContent), 'short passphrase refused'); ok(!saved, 'nothing saved');
set('pass', 'a long enough passphrase'); set('pass2', 'different one here!!'); submit();
ok(/do not match/.test(box.textContent), 'mismatch refused');
set('pass', 'a long enough passphrase'); set('pass2', 'a long enough passphrase'); submit();
await new Promise((r) => setTimeout(r, 50));
ok(saved === 'p.zip', 'saved after valid passphrase'); ok(opts.passphrase === 'a long enough passphrase' && opts.includeDocuments && !opts.includeRestricted, 'options passed');
ok(db._log.some((l) => l.kind === 'rpc' && l.name === 'log_export'), 'audit rpc attempted');
ok(/Not recorded in the audit log yet/.test(box.textContent), 'missing rpc is reported, not fatal');
db._rpc.log_export = async () => null;
box.querySelector('[data-again]').click(); saved = null;
set('pass', ''); set('pass2', ''); form().elements.licence.checked = true; submit();
ok(document.getElementById('dialog').hasAttribute('open') && /without a passphrase/i.test(document.getElementById('dialog').textContent), 'confirmation asked');
ok(/licence numbers/.test(document.getElementById('dialog').textContent), 'confirmation mentions licence data');
document.getElementById('dialog').querySelector('form').dispatchEvent(new window.Event('submit', { cancelable: true, bubbles: true }));
await new Promise((r) => setTimeout(r, 80));
ok(saved === 'p.zip' && opts.includeRestricted && !opts.passphrase, 'unlocked run after confirming');
ok(/Recorded in the audit log/.test(box.textContent), 'recorded when rpc exists');
console.log(bad ? `${bad} failed` : 'exit screen: all passed'); process.exit(bad ? 1 : 0);
